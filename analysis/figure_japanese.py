def localize(text):
    # Japanese stays outside mathtext, which does not support CJK in formulas.
    if text in ('H','L'):
        return 'Hi' if text=='H' else 'Lo'
    result=[]
    for part in re.split(r'(\$[^$]*\$)',str(text)):
        if part.startswith('$') and part.endswith('$'):
            part=part.replace('High','Hi').replace('Low','Lo')
            part=part.replace(r'P(H\mid',r'P(\mathrm{Hi}\mid').replace(r'P(L\mid',r'P(\mathrm{Lo}\mid')
            part=part.replace(r'\mathrm{no\ role}',r'\mathrm{none}').replace(r'\mathrm{particular\ completed\ role}\ r',r'R=r')
            part=part.replace(r'\mathrm{fair}',r'\mathrm{F}')
            result.append(part)
        else:
            for original,japanese in ORDERED:
                # The shortest English tokens require word boundaries.
                if original in ('or','and','fair','Fair','High','Low','Win','Draw','Loss','Role','Stop'):
                    part=re.sub(r'\b'+re.escape(original)+r'\b',lambda _:japanese,part)
                else:
                    part=part.replace(original,japanese)
            result.append(part)
    return ''.join(result)
